#!/usr/bin/env python3
"""
Multi-model ROC and precision-recall curves for PIDS-Bench v3.

Covers three evaluation contexts:
  1. IID test set (test.csv)         — ROC-AUC and PR-AUC across all models
  2. Structural OOD (structural_ood.csv) — ROC-AUC and PR-AUC where prob CSVs exist
  3. Hard-benign score distribution  — probability density per model (ROC is undefined
                                       on all-benign data; a score distribution is more
                                       informative and honest for this split)

Models included when probability CSVs are available
----------------------------------------------------
  deberta_v3   : outputs/deberta_v3/{test,structural_ood}_predictions*.csv
  distilbert   : outputs/distilbert_baseline/{test,structural_ood}_predictions*.csv
  tfidf_logreg : outputs/tfidf_baseline/{test,structural_ood}_probability_scores.csv
                 (generated by eval/generate_probability_scores.py)

Output layout (outputs/roc_pr_curves/)
---------------------------------------
  roc_test.pdf / .png              — multi-model ROC for test split
  pr_test.pdf  / .png              — multi-model PR for test split
  roc_structural_ood.pdf / .png    — multi-model ROC for structural_ood
  pr_structural_ood.pdf  / .png    — multi-model PR for structural_ood
  score_dist_hard_benign.pdf / .png — score density on hard-benign set
  roc_pr_summary.csv               — ROC-AUC and PR-AUC per model per split
  roc_pr_summary.json

Usage
-----
  python eval/plot_roc_pr_curves.py
  python eval/plot_roc_pr_curves.py --splits test structural_ood
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.ticker as ticker
import numpy as np
import pandas as pd
from sklearn.metrics import (
    average_precision_score,
    precision_recall_curve,
    roc_auc_score,
    roc_curve,
)

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OUT_DIR = ROOT / "outputs" / "roc_pr_curves"

# ──────────────────────────────────────────────────────────────────────────────
# Model registry
# Each entry: (display_name, color, prob_csv_for_split)
# The callable takes the split name and returns the Path to the probability CSV.
# ──────────────────────────────────────────────────────────────────────────────
def _deberta_path(split: str) -> Path:
    base = ROOT / "outputs" / "deberta_v3"
    candidates = [
        base / f"{split}_predictions.csv",
        base / f"{split}_probability_scores.csv",
    ]
    for p in candidates:
        if p.exists():
            return p
    return candidates[0]   # will fail clearly in load_probs


def _distilbert_path(split: str) -> Path:
    base = ROOT / "outputs" / "distilbert_baseline"
    candidates = [
        base / f"{split}_predictions.csv",
        base / f"{split}_probability_scores.csv",
    ]
    for p in candidates:
        if p.exists():
            return p
    return candidates[0]


def _tfidf_path(split: str) -> Path:
    base = ROOT / "outputs" / "tfidf_baseline"
    # The original tfidf CSVs have no probability_score; the generated ones do.
    candidates = [
        base / f"{split}_probability_scores.csv",
        base / f"{split}_predictions.csv",
    ]
    for p in candidates:
        if p.exists():
            return p
    return candidates[0]


def _gpt4o_mini_path(split: str) -> Path:
    # GPT-4o-mini outputs use split names: test, structural_ood, domain_ood, etc.
    base = ROOT / "outputs" / "external_eval" / "multiaxis" / "gpt4o_mini"
    p = base / f"{split}.csv"
    return p


MODEL_REGISTRY: list[dict] = [
    {"model_id": "deberta_v3",   "display": "DeBERTa-v3",          "color": "#1a6faf", "path_fn": _deberta_path},
    {"model_id": "distilbert",   "display": "DistilBERT",           "color": "#e07b39", "path_fn": _distilbert_path},
    {"model_id": "tfidf_logreg", "display": "TF-IDF + LR",          "color": "#2ca02c", "path_fn": _tfidf_path},
    {"model_id": "gpt4o_mini",   "display": "GPT-4o-mini (0-shot)", "color": "#9467bd", "path_fn": _gpt4o_mini_path},
]


# ──────────────────────────────────────────────────────────────────────────────
# Data loading
# ──────────────────────────────────────────────────────────────────────────────

def load_probs(csv_path: Path) -> tuple[np.ndarray, np.ndarray] | None:
    """Return (y_true, y_prob) or None if file missing / no prob column."""
    if not csv_path.exists():
        return None
    df = pd.read_csv(csv_path)
    if "probability_score" not in df.columns:
        return None
    y_prob = pd.to_numeric(df["probability_score"], errors="coerce").to_numpy()
    if not np.isfinite(y_prob).all():
        return None
    y_prob = np.clip(y_prob, 0.0, 1.0)

    if "true_label" in df.columns:
        y_true = df["true_label"].astype(int).to_numpy()
    elif "label" in df.columns:
        y_true = df["label"].astype(int).to_numpy()
    else:
        return None

    return y_true, y_prob


# ──────────────────────────────────────────────────────────────────────────────
# Plotting utilities
# ──────────────────────────────────────────────────────────────────────────────

def _fig_layout() -> tuple:
    fig, ax = plt.subplots(figsize=(7, 5.5))
    ax.grid(color="#e5e5e5", lw=0.7, zorder=0)
    return fig, ax


def _save_fig(fig: plt.Figure, out_pdf: Path, out_png: Path) -> None:
    fig.tight_layout()
    fig.savefig(out_pdf, format="pdf", bbox_inches="tight")
    fig.savefig(out_png, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved {out_pdf.relative_to(ROOT)}")
    print(f"  Saved {out_png.relative_to(ROOT)}")


def plot_roc(
    model_curves: list[dict],  # each: {display, color, fpr, tpr, auc}
    split_name: str,
    out_pdf: Path,
    out_png: Path,
) -> None:
    fig, ax = _fig_layout()
    ax.plot([0, 1], [0, 1], lw=1.0, ls="--", color="#aaaaaa", label="Random (AUC = 0.5000)")
    for mc in model_curves:
        ax.plot(mc["fpr"], mc["tpr"], color=mc["color"], lw=2.0,
                label=f"{mc['display']}  (AUC = {mc['auc']:.4f})")

    ax.set_xlim(-0.01, 1.01)
    ax.set_ylim(-0.01, 1.01)
    ax.set_xlabel("False Positive Rate", fontsize=12)
    ax.set_ylabel("True Positive Rate", fontsize=12)
    split_label = split_name.replace("_", " ").title()
    ax.set_title(f"ROC Curves — {split_label} Split", fontsize=13)
    ax.legend(loc="lower right", fontsize=9.5, framealpha=0.9)
    _save_fig(fig, out_pdf, out_png)


def plot_pr(
    model_curves: list[dict],  # each: {display, color, prec, rec, ap}
    split_name: str,
    out_pdf: Path,
    out_png: Path,
) -> None:
    fig, ax = _fig_layout()
    for mc in model_curves:
        ax.plot(mc["rec"], mc["prec"], color=mc["color"], lw=2.0,
                label=f"{mc['display']}  (AP = {mc['ap']:.4f})")

    ax.set_xlim(-0.01, 1.01)
    ax.set_ylim(-0.01, 1.01)
    ax.set_xlabel("Recall", fontsize=12)
    ax.set_ylabel("Precision", fontsize=12)
    split_label = split_name.replace("_", " ").title()
    ax.set_title(f"Precision-Recall Curves — {split_label} Split", fontsize=13)
    ax.legend(loc="lower left", fontsize=9.5, framealpha=0.9)
    _save_fig(fig, out_pdf, out_png)


def plot_score_distribution_hard_benign(
    model_scores: list[dict],  # each: {display, color, probs}
    out_pdf: Path,
    out_png: Path,
) -> None:
    """
    Hard-benign is all-benign (no positive class) — ROC/PR is undefined.
    Instead, plot the distribution of model-assigned injection probability scores.
    A well-behaved model should assign scores clustered near 0.
    A model with high hard-benign FPR will have a heavy tail beyond its operating threshold.
    """
    fig, ax = _fig_layout()
    bins = np.linspace(0.0, 1.0, 51)
    for ms in model_scores:
        ax.hist(
            ms["probs"],
            bins=bins,
            density=True,
            color=ms["color"],
            alpha=0.45,
            label=ms["display"],
            histtype="stepfilled",
        )
        ax.hist(
            ms["probs"],
            bins=bins,
            density=True,
            color=ms["color"],
            histtype="step",
            lw=1.5,
        )

    ax.set_xlabel("Model-assigned injection probability score", fontsize=12)
    ax.set_ylabel("Density", fontsize=12)
    ax.set_title(
        "Hard-benign score distribution\n"
        "(all inputs are benign; scores near 0 indicate low false-positive pressure)",
        fontsize=11,
    )
    ax.legend(fontsize=9.5, framealpha=0.9)
    ax.set_xlim(-0.02, 1.02)
    _save_fig(fig, out_pdf, out_png)


# ──────────────────────────────────────────────────────────────────────────────
# Hard-benign path helpers
# ──────────────────────────────────────────────────────────────────────────────

def _hard_benign_path(model_id: str) -> Path:
    """Return the hard-benign probability CSV for a model."""
    base_map = {
        "deberta_v3":   ROOT / "outputs" / "deberta_v3",
        "distilbert":   ROOT / "outputs" / "distilbert_baseline",
        "tfidf_logreg": ROOT / "outputs" / "tfidf_baseline",
        "gpt4o_mini":   ROOT / "outputs" / "external_eval" / "multiaxis" / "gpt4o_mini",
    }
    base = base_map[model_id]
    # GPT-4o-mini uses the split filename directly: hard_benign.csv
    if model_id == "gpt4o_mini":
        p = base / "hard_benign.csv"
        return p
    for fname in ("hard_benign_predictions.csv", "hard_benign_probability_scores.csv"):
        p = base / fname
        if p.exists():
            return p
    return base / "hard_benign_probability_scores.csv"


# ──────────────────────────────────────────────────────────────────────────────
# Main
# ──────────────────────────────────────────────────────────────────────────────

def main() -> None:
    ap = argparse.ArgumentParser(description="Multi-model ROC/PR curves for PIDS-Bench")
    ap.add_argument(
        "--splits",
        nargs="+",
        default=["test", "structural_ood"],
        help="Splits to plot ROC/PR for (default: test structural_ood)",
    )
    ap.add_argument(
        "--no-hard-benign",
        action="store_true",
        help="Skip hard-benign score distribution plot",
    )
    args = ap.parse_args()

    import os
    os.chdir(ROOT)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    summary_rows: list[dict] = []

    # ── ROC and PR curves per split ───────────────────────────────────────────
    for split in args.splits:
        print(f"\n=== Split: {split} ===")
        roc_curves: list[dict] = []
        pr_curves:  list[dict] = []

        for spec in MODEL_REGISTRY:
            path = spec["path_fn"](split)
            result = load_probs(path)
            if result is None:
                print(f"  [{spec['model_id']}] SKIP — {path.relative_to(ROOT)} not found or missing prob column")
                continue
            y_true, y_prob = result

            # Must have both classes for ROC/PR
            if len(np.unique(y_true)) < 2:
                print(f"  [{spec['model_id']}] SKIP — single-class data (n_classes={len(np.unique(y_true))})")
                continue

            # ROC
            fpr_arr, tpr_arr, _ = roc_curve(y_true, y_prob)
            auc = float(roc_auc_score(y_true, y_prob))
            roc_curves.append({"display": spec["display"], "color": spec["color"],
                                "fpr": fpr_arr, "tpr": tpr_arr, "auc": auc})

            # PR
            prec_arr, rec_arr, _ = precision_recall_curve(y_true, y_prob)
            ap = float(average_precision_score(y_true, y_prob))
            pr_curves.append({"display": spec["display"], "color": spec["color"],
                               "prec": prec_arr, "rec": rec_arr, "ap": ap})

            summary_rows.append({
                "model":    spec["model_id"],
                "split":    split,
                "n":        len(y_true),
                "n_pos":    int(y_true.sum()),
                "n_neg":    int((y_true == 0).sum()),
                "roc_auc":  round(auc, 6),
                "pr_ap":    round(ap, 6),
            })
            print(f"  [{spec['model_id']}] ROC-AUC={auc:.4f}  PR-AP={ap:.4f}  (n={len(y_true)})")

        if not roc_curves:
            print(f"  No models with probability scores found for split '{split}'. "
                  "Run eval/generate_probability_scores.py first.")
            continue

        # Plot ROC
        plot_roc(
            roc_curves, split,
            OUT_DIR / f"roc_{split}.pdf",
            OUT_DIR / f"roc_{split}.png",
        )
        # Plot PR
        plot_pr(
            pr_curves, split,
            OUT_DIR / f"pr_{split}.pdf",
            OUT_DIR / f"pr_{split}.png",
        )

    # ── Hard-benign score distribution ───────────────────────────────────────
    if not args.no_hard_benign:
        print("\n=== Hard-benign score distribution ===")
        hb_scores: list[dict] = []
        for spec in MODEL_REGISTRY:
            path = _hard_benign_path(spec["model_id"])
            result = load_probs(path)
            if result is None:
                print(f"  [{spec['model_id']}] SKIP — {path.relative_to(ROOT)} not found")
                continue
            _, y_prob = result
            hb_scores.append({"display": spec["display"], "color": spec["color"],
                               "probs": y_prob})
            print(f"  [{spec['model_id']}] n={len(y_prob)}, "
                  f"median={np.median(y_prob):.4f}, "
                  f"p90={np.percentile(y_prob, 90):.4f}")

        if hb_scores:
            plot_score_distribution_hard_benign(
                hb_scores,
                OUT_DIR / "score_dist_hard_benign.pdf",
                OUT_DIR / "score_dist_hard_benign.png",
            )
        else:
            print("  No hard-benign probability scores found.")

    # ── Summary table ─────────────────────────────────────────────────────────
    if summary_rows:
        df_summary = pd.DataFrame(summary_rows)
        df_summary.to_csv(OUT_DIR / "roc_pr_summary.csv", index=False)
        with open(OUT_DIR / "roc_pr_summary.json", "w") as f:
            json.dump(summary_rows, f, indent=2)
        print(f"\nSummary saved to {(OUT_DIR / 'roc_pr_summary.csv').relative_to(ROOT)}")
        print("\n" + df_summary.to_string(index=False))
    else:
        print("\nNo summary rows — no probability CSVs were found.")
        print("Run eval/generate_probability_scores.py to generate TF-IDF probability CSVs.")


if __name__ == "__main__":
    main()
